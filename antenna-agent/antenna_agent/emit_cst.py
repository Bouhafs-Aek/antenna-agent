"""IR -> CST Studio Suite: VBA history macros (.bas) + a Python driver using cst.interface / cst.results."""
from __future__ import annotations

from .model import Box, Cyl, Model


def _f(x: float) -> str:
    return f"{x:.6f}"


def history(m: Model) -> list[tuple[str, str]]:
    h: list[tuple[str, str]] = []
    h.append(("define units", 'With Units\n .Reset\n .Geometry "mm"\n .Frequency "GHz"\n .Time "ns"\nEnd With'))
    h.append(("define frequency range", f'Solver.FrequencyRange "{_f(m.fmin)}", "{_f(m.fmax)}"'))
    for name, (er, tand) in m.materials.items():
        h.append((f"define material {name}",
                  f'With Material\n .Reset\n .Name "{name}"\n .Folder ""\n .Type "Normal"\n'
                  f' .Epsilon "{er}"\n .Mu "1"\n .TanD "{tand}"\n .TanDFreq "{_f(m.f0)}"\n'
                  f' .TanDGiven "True"\n .TanDModel "ConstTanD"\n .Colour "0.2", "0.6", "0.3"\n .Create\nEnd With'))
    for s in m.solids:
        mat = "PEC" if s.material == "pec" else s.material
        if isinstance(s, Box):
            h.append((f"define brick {s.name}",
                      f'With Brick\n .Reset\n .Name "{s.name}"\n .Component "ant"\n .Material "{mat}"\n'
                      f' .Xrange "{_f(s.lo[0])}", "{_f(s.hi[0])}"\n .Yrange "{_f(s.lo[1])}", "{_f(s.hi[1])}"\n'
                      f' .Zrange "{_f(s.lo[2])}", "{_f(s.hi[2])}"\n .Create\nEnd With'))
        elif isinstance(s, Cyl):
            h.append((f"define cylinder {s.name}",
                      f'With Cylinder\n .Reset\n .Name "{s.name}"\n .Component "ant"\n .Material "{mat}"\n'
                      f' .OuterRadius "{_f(s.r)}"\n .InnerRadius "0.0"\n .Axis "z"\n'
                      f' .Zrange "{_f(s.z0)}", "{_f(s.z1)}"\n .Xcenter "{_f(s.xc)}"\n .Ycenter "{_f(s.yc)}"\n'
                      f' .Segments "0"\n .Create\nEnd With'))
    for b in m.booleans:
        for tool in b.tools:
            verb = "Subtract" if b.op == "subtract" else "Add"
            h.append((f"boolean {b.op} {b.target} {tool}", f'Solid.{verb} "ant:{b.target}", "ant:{tool}"'))
    p = m.port
    h.append(("define discrete port",
              f'With DiscretePort\n .Reset\n .PortNumber "1"\n .Type "SParameter"\n .Label ""\n .Folder ""\n'
              f' .Impedance "{p.z0}"\n .VoltagePortImpedance "0.0"\n .Voltage "1.0"\n .Current "1.0"\n'
              f' .Monitor "True"\n .Radius "0.0"\n'
              f' .SetP1 "False", "{_f(p.p1[0])}", "{_f(p.p1[1])}", "{_f(p.p1[2])}"\n'
              f' .SetP2 "False", "{_f(p.p2[0])}", "{_f(p.p2[1])}", "{_f(p.p2[2])}"\n'
              f' .InvertDirection "False"\n .LocalCoordinates "False"\n .Wire ""\n .Position "end1"\n .Create\nEnd With'))
    h.append(("define open boundaries",
              'With Boundary\n .Xmin "expanded open"\n .Xmax "expanded open"\n .Ymin "expanded open"\n'
              ' .Ymax "expanded open"\n .Zmin "expanded open"\n .Zmax "expanded open"\n'
              ' .Xsymmetry "none"\n .Ysymmetry "none"\n .Zsymmetry "none"\nEnd With'))
    for fm in (m.fields_ghz or [m.f0]):
        h.append((f"define farfield monitor {fm}",
                  f'With Monitor\n .Reset\n .Name "farfield (f={_f(fm)})"\n .Domain "Frequency"\n'
                  f' .FieldType "Farfield"\n .MonitorValue "{_f(fm)}"\n .ExportFarfieldSource "False"\n'
                  f' .UseSubvolume "False"\n .Create\nEnd With'))
    return h


def emit_bas(m: Model) -> str:
    """Plain VBA. In CST: Home > Macros > (run macro), or paste into the history list. No Python needed."""
    out = ["' Generated by antenna_agent. Run inside CST Microwave Studio.", "Sub Main()"]
    for name, vba in history(m):
        out.append(f"  ' {name}")
        out += ["  " + line for line in vba.splitlines()]
    out += ["  Solver.Start", "End Sub"]
    return "\n".join(out)


DRIVER = '''\
"""Generated by antenna_agent. Needs CST Studio Suite (2021+) and its `cst` Python package."""
import csv, sys
from pathlib import Path

import cst.interface as ci
import cst.results as cr

OUT = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
OUT.mkdir(parents=True, exist_ok=True)
PROJECT = OUT / "antenna.cst"
HISTORY = {history!r}

de = ci.DesignEnvironment.new() if hasattr(ci.DesignEnvironment, "new") else ci.DesignEnvironment()
try:
    prj = de.new_mws()
    for name, vba in HISTORY:
        prj.model3d.add_to_history(name, vba)
    try:
        prj.save(str(PROJECT), allow_overwrite=True)
    except TypeError:
        prj.save(str(PROJECT))
    prj.model3d.run_solver()
    prj.save()
    res = cr.ProjectFile(str(PROJECT), allow_interactive=True)
    item = res.get_3d().get_result_item(r"1D Results\\S-Parameters\\S1,1")
    f, s = item.get_xdata(), item.get_ydata()          # f in GHz (Units.Frequency), s complex
    with open(OUT / "s11.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["f_GHz", "re", "im"])
        w.writerows((fi, complex(si).real, complex(si).imag) for fi, si in zip(f, s))
finally:
    de.close()
'''


def emit_driver(m: Model) -> str:
    return DRIVER.replace("{history!r}", repr(history(m)))
